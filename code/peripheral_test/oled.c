static char    g_shadow[OLED_ROWS][OLED_COLS];   /* what is currently on screen */
static uint8_t g_bar_last = 0xFF;

/* ---- low level: command / data transfers ---- */
static int begin(uint8_t control)               /* 0x00 = commands, 0x40 = data */
{
    return i2c_start_write(OLED_ADDR) && i2c_put(control);
}

static int send_cmds(const uint8_t *c, unsigned n)
{
    if (!begin(0x00)) return 0;
    for (unsigned i = 0; i < n; i++) {
        if (!i2c_put(c[i])) return 0;
    }
    return i2c_stop();
}

static int goto_row(unsigned row)
{
    uint8_t c[3] = { (uint8_t)(0xB0u | row), 0x00, 0x10 };   /* page, column 0 */
    return send_cmds(c, 3);
}

static const uint8_t *glyph(char ch)
{
    if (ch >= 'a' && ch <= 'z') ch = (char)(ch - 'a' + 'A');
    if (ch < 0x20 || ch > 0x5A) ch = ' ';
    return &font5x7[(unsigned)(ch - 0x20) * 5u];
}


int oled_text(unsigned row, const char *s)
{
    char buf[OLED_COLS];
    int same = 1;

    if (row >= OLED_ROWS) return 0;
    for (unsigned i = 0; i < OLED_COLS; i++) {
        char ch = *s ? *s++ : ' ';
        buf[i] = ch;
        if (ch != g_shadow[row][i]) same = 0;
    }
    if (same) return 1;

    if (!goto_row(row) || !begin(0x40)) return 0;
    for (unsigned i = 0; i < OLED_COLS; i++) {
        const uint8_t *g = glyph(buf[i]);
        for (unsigned k = 0; k < 5; k++) {
            if (!i2c_put(g[k])) return 0;
        }
        if (!i2c_put(0x00)) return 0;                        /* 1 px gap */
    }
    if (!i2c_put(0x00) || !i2c_put(0x00)) return 0;          /* pad 126 -> 128 columns */
    if (!i2c_stop()) return 0;

    for (unsigned i = 0; i < OLED_COLS; i++) g_shadow[row][i] = buf[i];
    return 1;
}

int oled_bar(unsigned row, uint8_t fill)
{
    if (row >= OLED_ROWS) return 0;
    if (fill > OLED_BAR_MAX) fill = OLED_BAR_MAX;
    if (fill == g_bar_last) return 1;

    if (!goto_row(row) || !begin(0x40)) return 0;
    for (unsigned col = 0; col < 128u; col++) {
        uint8_t b;
        if (col == 0 || col == 127u) b = 0xFF;
        else if (col <= fill)        b = 0x7E;
        else                         b = 0x42;
        if (!i2c_put(b)) return 0;
    }
    if (!i2c_stop()) return 0;
    g_bar_last = fill;
    return 1;
}

int oled_init(void)
{
    static const uint8_t init[] = {
        0xAE,                   /* display off */
        0xD5, 0x51,             /* clock divide / oscillator */
        0x20,                   /* page addressing mode */
        0x81, 0x4F,             /* contrast */
        0xAD, OLED_DCDC_CMD,    /* DC-DC setting */
        OLED_SEG_REMAP,
        OLED_COM_SCAN,
        0xDC, 0x00,             /* display start line */
        0xD3, 0x00,             /* display offset */
        0xA8, 0x7F,             /* multiplex ratio: 128 rows */
        0xD9, 0x22,             /* pre-charge */
        0xDB, 0x35,             /* VCOM deselect */
        0xA4,                   /* follow RAM content */
        0xA6                    /* normal (not inverted) */
    };
    static const uint8_t on = 0xAF;

    for (unsigned r = 0; r < OLED_ROWS; r++)
        for (unsigned c = 0; c < OLED_COLS; c++) g_shadow[r][c] = 0;   /* force full redraw */
    g_bar_last = 0xFF;

    if (!send_cmds(init, sizeof init)) return 0;
    for (unsigned r = 0; r < OLED_ROWS; r++)
        if (!oled_text(r, "")) return 0;        /* clear screen */
    delay_ms(100);
    return send_cmds(&on, 1);                   /* display on */
}
