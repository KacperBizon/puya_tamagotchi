/* ---- panel options (override with -D on the compiler command line) ---- */
#ifndef OLED_ADDR
#define OLED_ADDR       0x3C    /* 7-bit I2C address (some modules use 0x3D) */
#endif
#ifndef OLED_DCDC_CMD
#define OLED_DCDC_CMD   0x8A    /* DC-DC setting byte; try 0x8B if the panel stays dark */
#endif
#ifndef OLED_SEG_REMAP
#define OLED_SEG_REMAP  0xA0    /* 0xA1 mirrors the image horizontally */
#endif
#ifndef OLED_COM_SCAN
#define OLED_COM_SCAN   0xC0    /* 0xC8 flips the image vertically */
#endif

